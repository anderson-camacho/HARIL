import type { PlatformPath } from "node:path";

// Launchers under <root>/bin (M3-T3). They call the installed CLI by absolute path and never touch PATH.
// The Node executable is the isolated one from runtime/manifest.json when present, else `node` from PATH.

export const SHIM_NAMES = ["haril.cmd", "haril.ps1", "haril"] as const;
export type ShimName = (typeof SHIM_NAMES)[number];

export interface ShimInput {
  // Absolute directory of the installed release (contains haril.mjs).
  readonly appDir: string;
  // Absolute Node executable, or null to use `node` from PATH.
  readonly nodeExe: string | null;
  readonly pathOps: PlatformPath;
}

export function shimContents(input: ShimInput): Record<ShimName, string> {
  const entry = input.pathOps.join(input.appDir, "haril.mjs");
  const cmdNode = input.nodeExe === null ? "node" : `"${input.nodeExe}"`;
  const psNode = input.nodeExe === null ? "node" : `'${input.nodeExe.replaceAll("'", "''")}'`;
  const shNode = input.nodeExe === null ? "node" : `"${input.nodeExe}"`;
  const psEntry = `'${entry.replaceAll("'", "''")}'`;
  const note = "Generated by haril-bootstrap install. Runs the installed CLI; PATH is not edited.";
  return {
    "haril.cmd": [
      "@echo off",
      `rem ${note}`,
      `${cmdNode} "${entry}" %*`,
      "exit /b %ERRORLEVEL%",
      "",
    ].join("\r\n"),
    "haril.ps1": [`# ${note}`, `& ${psNode} ${psEntry} @args`, "exit $LASTEXITCODE", ""].join(
      "\r\n",
    ),
    haril: ["#!/bin/sh", `# ${note}`, `exec ${shNode} "${entry}" "$@"`, ""].join("\n"),
  };
}
