// Pixel shader for the optional Windows Terminal profile (`haril-bootstrap terminal-profile`). It is a reduced,
// readability-first variant of crt.hlsl from https://github.com/Hammster/windows-terminal-shaders (CC0 1.0): only
// the bloom and scanline passes are kept, both softened. The scanline pass comes from Microsoft Terminal's
// samples/PixelShaders/Retro.hlsl (MIT); see THIRD_PARTY_NOTICES.md. Time is never read, so Windows Terminal does
// not redraw continuously and the shader costs nothing while the screen is idle.

export const TERMINAL_SHADER_NAMES = ["crt"] as const;
export type TerminalShaderName = (typeof TERMINAL_SHADER_NAMES)[number];

export function isTerminalShaderName(value: string | undefined): value is TerminalShaderName {
  return TERMINAL_SHADER_NAMES.some((name) => name === value);
}

const CRT_SOFT = `// HARIL soft CRT for Windows Terminal. Generated by haril-bootstrap terminal-profile.
// Derived from crt.hlsl by Hammster (CC0 1.0), https://github.com/Hammster/windows-terminal-shaders
// Scanlines from Microsoft Terminal samples/PixelShaders/Retro.hlsl, Copyright (c) Microsoft Corporation, MIT License.

Texture2D shaderTexture : register(t0);
SamplerState samplerState : register(s0);

cbuffer PixelShaderSettings : register(b0) {
  float  Time;
  float  Scale;
  float2 Resolution;
  float4 Background;
};

struct PSInput {
  float4 pos : SV_POSITION;
  float2 uv : TEXCOORD0;
};

#define BLOOM_OFFSET     0.0015
#define BLOOM_STRENGTH   0.35
#define SCANLINE_FACTOR  0.12

float3 bloom(float3 color, float2 uv)
{
  float3 edge = color - shaderTexture.Sample(samplerState, uv + float2(-BLOOM_OFFSET, 0) * Scale).rgb;
  return saturate(color + edge * BLOOM_STRENGTH);
}

float3 scanlines(float3 color, float2 pos)
{
  float wave = 1 - (floor(pos.y / Scale) % 2) * SCANLINE_FACTOR;
  return saturate(color * wave);
}

float4 main(PSInput pin) : SV_TARGET
{
  float4 color = shaderTexture.Sample(samplerState, pin.uv);
  color.rgb = bloom(color.rgb, pin.uv);
  color.rgb = scanlines(color.rgb, pin.pos.xy);
  return color;
}
`;

export function terminalShaderSource(name: TerminalShaderName): string {
  switch (name) {
    case "crt":
      return CRT_SOFT;
  }
}
